/** `iconResolver` for unfold-nav: turns Lucide names (`'House'`) into SVG elements. */
export function lucide(name: string): SVGElement | null {
  const node = ICONS[name];
  return node ? createElement(node, { 'stroke-width': 1.75, 'aria-hidden': 'true' }) : null;
}

export const lucideMarkup = (name: string) => lucide(name)?.outerHTML ?? '';
